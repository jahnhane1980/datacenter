create or replace view "public"."vw_global_liquidity_score" as  WITH global_dates AS (
         SELECT macro_indicator_values.observation_date
           FROM public.macro_indicator_values
        UNION
         SELECT global_macro_indicator_values.observation_date
           FROM public.global_macro_indicator_values
        ), daily_data AS (
         SELECT d.observation_date,
            us.fed_net_liquidity,
            ( SELECT v.raw_value
                   FROM (public.global_macro_indicator_values v
                     JOIN public.global_macro_indicator_definition def ON ((v.indicator_id = def.id)))
                  WHERE (((def.series_id)::text = 'ECBASSETSW'::text) AND (v.observation_date <= d.observation_date))
                  ORDER BY v.observation_date DESC
                 LIMIT 1) AS ecb_assets_eur,
            ( SELECT v.raw_value
                   FROM (public.global_macro_indicator_values v
                     JOIN public.global_macro_indicator_definition def ON ((v.indicator_id = def.id)))
                  WHERE (((def.series_id)::text = 'JPNASSETS'::text) AND (v.observation_date <= d.observation_date))
                  ORDER BY v.observation_date DESC
                 LIMIT 1) AS boj_assets_jpy_100m,
            ( SELECT v.raw_value
                   FROM (public.global_macro_indicator_values v
                     JOIN public.global_macro_indicator_definition def ON ((v.indicator_id = def.id)))
                  WHERE (((def.series_id)::text = 'WLRRAFOIAL'::text) AND (v.observation_date <= d.observation_date))
                  ORDER BY v.observation_date DESC
                 LIMIT 1) AS foreign_repo_usd,
            ( SELECT fx.rate
                   FROM public.fx_rates_daily fx
                  WHERE (((fx.currency_pair)::text = 'EURUSD'::text) AND (fx.observation_date <= d.observation_date))
                  ORDER BY fx.observation_date DESC
                 LIMIT 1) AS eurusd_rate,
            ( SELECT fx.rate
                   FROM public.fx_rates_daily fx
                  WHERE (((fx.currency_pair)::text = 'USDJPY'::text) AND (fx.observation_date <= d.observation_date))
                  ORDER BY fx.observation_date DESC
                 LIMIT 1) AS usdjpy_rate
           FROM (global_dates d
             LEFT JOIN public.vw_us_liquidity_score us ON ((d.observation_date = us.observation_date)))
        )
 SELECT observation_date,
    fed_net_liquidity,
    (ecb_assets_eur * eurusd_rate) AS ecb_assets_usd,
    ((boj_assets_jpy_100m * (100)::numeric) / NULLIF(usdjpy_rate, (0)::numeric)) AS boj_assets_usd,
    foreign_repo_usd,
    (((COALESCE(fed_net_liquidity, (0)::numeric) + COALESCE((ecb_assets_eur * eurusd_rate), (0)::numeric)) + COALESCE(((boj_assets_jpy_100m * (100)::numeric) / NULLIF(usdjpy_rate, (0)::numeric)), (0)::numeric)) - COALESCE(foreign_repo_usd, (0)::numeric)) AS global_net_liquidity_usd
   FROM daily_data
  ORDER BY observation_date DESC;


create or replace view "public"."vw_liquidity_ampel" as  WITH daily_options AS (
         SELECT date(option_chain_snapshots.scraped_at) AS obs_date,
            sum(
                CASE
                    WHEN ((option_chain_snapshots.option_type)::text = 'PUT'::text) THEN option_chain_snapshots.volume
                    ELSE (0)::bigint
                END) AS put_volume,
            sum(
                CASE
                    WHEN ((option_chain_snapshots.option_type)::text = 'CALL'::text) THEN option_chain_snapshots.volume
                    ELSE (0)::bigint
                END) AS call_volume,
                CASE
                    WHEN (sum(
                    CASE
                        WHEN ((option_chain_snapshots.option_type)::text = 'CALL'::text) THEN option_chain_snapshots.volume
                        ELSE (0)::bigint
                    END) > (0)::numeric) THEN round((sum(
                    CASE
                        WHEN ((option_chain_snapshots.option_type)::text = 'PUT'::text) THEN option_chain_snapshots.volume
                        ELSE (0)::bigint
                    END) / sum(
                    CASE
                        WHEN ((option_chain_snapshots.option_type)::text = 'CALL'::text) THEN option_chain_snapshots.volume
                        ELSE (0)::bigint
                    END)), 2)
                    ELSE 1.00
                END AS put_call_ratio
           FROM public.option_chain_snapshots
          GROUP BY (date(option_chain_snapshots.scraped_at))
        ), liquidity_momentum AS (
         SELECT vw_us_liquidity_score.observation_date,
            vw_us_liquidity_score.fed_net_liquidity,
            vw_us_liquidity_score.tga_balance,
            lag(vw_us_liquidity_score.fed_net_liquidity, 5) OVER (ORDER BY vw_us_liquidity_score.observation_date) AS liq_5d_ago
           FROM public.vw_us_liquidity_score
        )
 SELECT l.observation_date,
    l.fed_net_liquidity,
    (l.fed_net_liquidity - l.liq_5d_ago) AS liq_momentum_5d,
    COALESCE(o.put_call_ratio, 1.00) AS put_call_ratio,
        CASE
            WHEN (((l.fed_net_liquidity - l.liq_5d_ago) < ('-50000'::integer)::numeric) AND (COALESCE(o.put_call_ratio, 1.00) > 1.10)) THEN 'ROT (Raus hier / Hedgen)'::text
            WHEN (((l.fed_net_liquidity - l.liq_5d_ago) < (0)::numeric) OR (COALESCE(o.put_call_ratio, 1.00) > 1.00)) THEN 'GELB (Vorsicht / Stop Loss anpassen)'::text
            ELSE 'GRÜN (Risk On)'::text
        END AS ampel_status
   FROM (liquidity_momentum l
     LEFT JOIN daily_options o ON ((l.observation_date = o.obs_date)))
  ORDER BY l.observation_date DESC;


