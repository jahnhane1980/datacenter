CREATE OR REPLACE FUNCTION public.get_missing_sentiment_dates(target_ticker text, start_date date, exclude_weekends boolean)
 RETURNS TABLE(missing_date date)
 LANGUAGE plpgsql
AS $function$
BEGIN
  RETURN QUERY
  WITH date_series AS (
    -- Erstellt den perfekten Kalender vom Startdatum bis heute
    SELECT generate_series(start_date, CURRENT_DATE, '1 day'::interval)::date AS gs_date
  ),
  filtered_series AS (
    -- Filtert Wochenenden heraus, wenn exclude_weekends TRUE ist (ISODOW 6=Sa, 7=So)
    SELECT gs_date
    FROM date_series
    WHERE (exclude_weekends = false) OR (EXTRACT(ISODOW FROM gs_date) < 6)
  )
  -- Gleicht den perfekten Kalender mit deiner Tabelle ab und gibt nur die Lücken zurück
  SELECT f.gs_date
  FROM filtered_series f
  LEFT JOIN public.market_sentiment_daily m
    ON m.observation_date = f.gs_date AND m.ticker = target_ticker
  WHERE m.observation_date IS NULL
  ORDER BY f.gs_date ASC;
END;
$function$
;

create or replace view "public"."labor_market_divergence_matrix" as  WITH adp_raw AS (
         SELECT labor_market_data_points.data_period,
            labor_market_data_points.value AS adp_level
           FROM public.labor_market_data_points
          WHERE ((labor_market_data_points.series_id)::text = 'ADPMNUSNERSA'::text)
        ), adp_mom AS (
         SELECT adp_raw.data_period,
            (adp_raw.adp_level - lag(adp_raw.adp_level) OVER (ORDER BY adp_raw.data_period)) AS adp_new_jobs
           FROM adp_raw
        ), nfp_raw AS (
         SELECT labor_market_data_points.data_period,
            labor_market_data_points.value AS nfp_level_k,
            labor_market_data_points.is_preliminary
           FROM public.labor_market_data_points
          WHERE ((labor_market_data_points.series_id)::text = 'PAYEMS'::text)
        ), nfp_mom AS (
         SELECT nfp_raw.data_period,
            nfp_raw.is_preliminary,
            ((nfp_raw.nfp_level_k - lag(nfp_raw.nfp_level_k) OVER (ORDER BY nfp_raw.data_period)) * (1000)::numeric) AS nfp_new_jobs
           FROM nfp_raw
        ), unrate AS (
         SELECT labor_market_data_points.data_period,
            labor_market_data_points.value AS unrate_value
           FROM public.labor_market_data_points
          WHERE ((labor_market_data_points.series_id)::text = 'UNRATE'::text)
        ), icsa_monthly AS (
         SELECT (date_trunc('month'::text, (labor_market_data_points.data_period)::timestamp with time zone))::date AS data_period,
            round(avg(labor_market_data_points.value)) AS weekly_claims_avg
           FROM public.labor_market_data_points
          WHERE ((labor_market_data_points.series_id)::text = 'ICSA'::text)
          GROUP BY ((date_trunc('month'::text, (labor_market_data_points.data_period)::timestamp with time zone))::date)
        )
 SELECT nfp_mom.data_period AS period,
    adp_mom.adp_new_jobs,
    nfp_mom.nfp_new_jobs AS nfp_preliminary,
    (nfp_mom.nfp_new_jobs - adp_mom.adp_new_jobs) AS divergence_raw,
    unrate.unrate_value,
    icsa_monthly.weekly_claims_avg,
    nfp_mom.is_preliminary
   FROM (((nfp_mom
     LEFT JOIN adp_mom ON ((nfp_mom.data_period = adp_mom.data_period)))
     LEFT JOIN unrate ON ((nfp_mom.data_period = unrate.data_period)))
     LEFT JOIN icsa_monthly ON ((nfp_mom.data_period = icsa_monthly.data_period)))
  ORDER BY nfp_mom.data_period DESC;


create or replace view "public"."vw_treasury_liquidity_mix" as  SELECT issue_date AS observation_date,
    sum(
        CASE
            WHEN ((security_type)::text = 'Bill'::text) THEN total_accepted
            ELSE (0)::numeric
        END) AS tbill_amount,
    sum(
        CASE
            WHEN ((security_type)::text = ANY (ARRAY[('Note'::character varying)::text, ('Bond'::character varying)::text])) THEN total_accepted
            ELSE (0)::numeric
        END) AS coupon_amount,
    sum(total_accepted) AS total_issuance,
        CASE
            WHEN (sum(total_accepted) > (0)::numeric) THEN round(((sum(
            CASE
                WHEN ((security_type)::text = 'Bill'::text) THEN total_accepted
                ELSE (0)::numeric
            END) / sum(total_accepted)) * (100)::numeric), 2)
            ELSE 0.00
        END AS tbill_ratio_percent
   FROM public.treasury_auctions
  WHERE (issue_date IS NOT NULL)
  GROUP BY issue_date
  ORDER BY issue_date DESC;


